# общий объем и вместимость одной единицы
total = int(input("Введите общий объем (например, количество студентов): "))
one = int(input("Введите вместимость единицы (например, мест в автобусе): "))
# количество полностью заполненных единиц
full_units = total // one
# остаток
remainder = total % one
# минимальное число
min_units = (total + one - 1) // one
# результат
print(f"Полностью заполненных единиц: {full_units}")
print(f"Остаток: {remainder}")
print(f"Минимальное число единиц для размещения: {min_units}")